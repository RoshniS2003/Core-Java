public class Variable {
    public static void main(String[] args) {
        // variables & primitive Data types
        String name = "Rani";
        double price = 20.25;

        name = "Roshni";

        System.out.println("Name:" + name);
        System.out.println("Price :" + price);

        int a = 10;
        int b = 20;
        int sum = a + b;
        System.out.println("Result :" + sum);
    }
}
