public class NonPrimitive {
    public static void main(String[] args) {
        String name = new String("Hello");
        System.out.println("Name:" + name);

        int[] marks = new int[3];
        marks[0] = 80;
        marks[1] = 89;
        marks[2] = 90;
        System.out.println(marks[0]);
        System.out.println(marks[1]);
        System.out.println(marks[2]);
    }
}
